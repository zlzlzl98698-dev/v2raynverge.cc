export const ALL_SECONDARY_TOPICS: SecondaryTopic[] = PRIMARY_CATEGORIES.flatMap(
  (cat) => cat.topics
);

export const ALL_TERTIARY_CLUSTERS: TertiaryCluster[] = ALL_SECONDARY_TOPICS.flatMap(
  (topic) => topic.clusters
);

export function getPrimaryCategoryBySlug(slug: string): PrimaryCategory | undefined {
  return PRIMARY_CATEGORIES.find((cat) => cat.id === slug);
}

export function getSecondaryTopic(
  parentSlug: string,
  topicSlug: string
): SecondaryTopic | undefined {
  const cat = getPrimaryCategoryBySlug(parentSlug);
  return cat?.topics.find((t) => t.slug === topicSlug);
}
